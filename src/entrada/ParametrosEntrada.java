public final class ParametrosEntrada {

    private final int N;
    private final int n;
    private final int A;
    private final int B;
    private final int H;

    public ParametrosEntrada(int N, int n, int A, int B, int H) {
        this.N = N;
        this.n = n;
        this.A = A;
        this.B = B;
        this.H = H;
    }

    public int getN() {
        return N;
    }

    public int getn() {
        return n;
    }

    public int getA() {
        return A;
    }

    public int getB() {
        return B;
    }

    public int getH() {
        return H;
    }
}