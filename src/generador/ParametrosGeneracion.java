public final class ParametrosGeneracion {

    private final int N;
    private final int n;
    private final int A;
    private final int B;

    public ParametrosGeneracion(int N, int n, int A, int B) {
        this.N = N;
        this.n = n;
        this.A = A;
        this.B = B;
    }

    public int getN() {
        return N;
    }

    public int getn() {
        return n;
    }

    public int getA() {
        return A;
    }

    public int getB() {
        return B;
    }
}